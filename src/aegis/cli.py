"""Command line interface: `aegis <command>`.

    aegis demo [--serve]           whole pipeline in one process, prints the incident report
    aegis train                    train + evaluate the ML models, write ml/reports/
    aegis run <service>            run one microservice (collector, auth-analyzer, ..., generator)
    aegis api                      run the REST API + dashboard (remote mode: Postgres + Kafka)
    aegis simulate <scenario>      publish a synthetic attack to the bus
    aegis generate --days N        write synthetic raw logs as JSON lines (for replay / inspection)
    aegis replay <file.jsonl>      publish raw logs from a file to the bus
    aegis rules validate           load every rule and run its embedded scenario tests
    aegis graph export-cypher      dump the entity graph as a Neo4j Cypher script
    aegis investigate <id>         (re)investigate an incident from the database
"""

from __future__ import annotations

import argparse
import json
import logging
import sys
from datetime import UTC, datetime, timedelta


def _print_incidents(repo, limit: int = 10) -> None:
    print(f"\n{'ID':>5}  {'LEVEL':<9} {'RISK':>5}  {'ALERTS':>6}  TITLE")
    for inc in repo.list_incidents(limit=limit):
        print(f"{inc.incident_id:>5}  {inc.risk_level:<9} {inc.risk_score:>5}  {len(inc.alert_ids):>6}  {inc.title}")


def _print_report(repo, incident_id: int) -> None:
    inc = repo.get_incident(incident_id)
    rep = repo.latest_report(incident_id)
    print("\n" + "=" * 100)
    print(f"Incident #{inc.incident_id}   Risk: {inc.risk_level} ({inc.risk_score})")
    print(f"Title: {inc.title}")
    ents = {}
    for e in inc.entities:
        ents.setdefault(e.type, []).append(e.value)
    print("Entities:")
    for t, vs in ents.items():
        print(f"  {t:<16} {', '.join(vs[:6])}")
    print("Timeline:")
    for a in repo.get_alerts(inc.alert_ids):
        tactic = a.mitre.tactic if a.mitre else "Anomaly (ML)"
        print(f"  {a.event_time:%H:%M:%S}  {tactic:<22} {a.rule_name}")
    print("Score breakdown:")
    for f in inc.score_breakdown:
        print(f"  +{f.points:<5} {f.reason}")
    if rep:
        r = rep[0]
        print(f"\nAI investigation (generated by {r.generated_by}, confidence {r.confidence}):")
        print(f"  {r.summary}")
        print("  Recommended actions:")
        for a in r.recommended_actions[:6]:
            print(f"   [{a.priority:>9}] {a.action}")
        print(f"  References: {', '.join(r.references[:4])}")
    print("=" * 100)


def cmd_demo(args) -> None:
    import os

    os.environ.setdefault("DATABASE_URL", "sqlite:///data/demo.db")
    from pathlib import Path

    db = os.environ["DATABASE_URL"]
    if db.startswith("sqlite:///") and not args.keep:
        Path(db.replace("sqlite:///", "")).unlink(missing_ok=True)

    from aegis.config import get_settings
    from aegis.pipeline import LocalPipeline
    from aegis.simulator import SCENARIOS

    settings = get_settings()
    pipeline = LocalPipeline(settings, use_llm=not args.no_llm)
    now = datetime.now(UTC)
    print(f"[1/3] Warming up baselines with {args.warmup_days} days of benign telemetry ...")
    scenarios = list(SCENARIOS) if args.scenario == "all" else [args.scenario]
    # attacks are spaced 90 minutes apart (> the 60-minute correlation window)
    first_attack = now - timedelta(minutes=90 * len(scenarios))
    n = pipeline.warm_up(days=args.warmup_days, end=first_attack - timedelta(minutes=10))
    print(f"      processed {n:,} bus messages")
    print(f"[2/3] Replaying attack scenario(s): {', '.join(scenarios)}")
    for i, name in enumerate(scenarios):
        pipeline.simulate(name, start=first_attack + timedelta(minutes=90 * i), seed=100 + i,
                          with_baseline_minutes=15)
    print("[3/3] Results")
    _print_incidents(pipeline.repo)
    top = sorted(pipeline.repo.list_incidents(limit=50), key=lambda i: (i.risk_score, len(i.alert_ids)), reverse=True)
    if top:
        _print_report(pipeline.repo, top[0].incident_id)
    if args.serve:
        import uvicorn

        from aegis.api import LiveFeeder, create_app

        if args.live:
            LiveFeeder(pipeline, attack_every_s=args.attack_every).start()
        print(f"\nDashboard: http://localhost:{args.port}  (Ctrl+C to stop)")
        uvicorn.run(create_app(pipeline, settings), host=args.host, port=args.port, log_level="warning")


def cmd_train(args) -> None:
    from aegis.ml.pipeline import train_and_evaluate

    report = train_and_evaluate(seed=args.seed)
    print(json.dumps({k: {m: v[m] for m in ("precision", "recall", "f1", "false_positive_rate")}
                      for k, v in report["results"].items()}, indent=2))
    print("Full report: ml/reports/REPORT.md")


def cmd_run(args) -> None:
    from aegis.services.runner import run_service

    run_service(args.service)


def cmd_api(args) -> None:
    import uvicorn

    from aegis.config import get_settings
    from aegis.observability import setup_logging, tracing

    s = get_settings()
    setup_logging(s.log_level, json_logs=True)
    tracing.setup_tracing("aegis-api", s.otel_endpoint)
    uvicorn.run("aegis.api:app_from_env", factory=True, host=args.host, port=args.port, log_level="info")


def cmd_simulate(args) -> None:
    from aegis.bus import create_bus
    from aegis.bus.base import RAW_TOPICS
    from aegis.simulator import run_scenario

    bus = create_bus()
    envs = run_scenario(args.scenario, datetime.now(UTC), seed=args.seed)
    for env in envs:
        bus.publish(RAW_TOPICS[env["source"]], env)
    bus.flush()
    print(f"published {len(envs)} raw records for scenario {args.scenario}")


def cmd_generate(args) -> None:
    from aegis.simulator import build_dataset

    for env in build_dataset(args.days, args.seed, attacks_per_day=args.attacks_per_day):
        sys.stdout.write(json.dumps(env) + "\n")


def cmd_replay(args) -> None:
    from aegis.bus import create_bus
    from aegis.bus.base import RAW_TOPICS

    bus = create_bus()
    n = 0
    with open(args.file) as fh:
        for line in fh:
            env = json.loads(line)
            bus.publish(RAW_TOPICS[env["source"]], env)
            n += 1
    bus.flush()
    print(f"replayed {n} records")


def cmd_rules(args) -> None:
    from aegis.collectors import normalize
    from aegis.config import get_settings
    from aegis.rules import RulesEngine, load_rules
    from aegis.simulator import run_scenario

    rules = load_rules(get_settings().rules_dir)
    print(f"{len(rules)} rules loaded OK")
    failures = 0
    for rule in rules:
        for t in rule.tests:
            engine = RulesEngine([rule])
            hits = [a for env in run_scenario(t["scenario"], datetime(2026, 9, 14, 14, 3, tzinfo=UTC), seed=1)
                    for a in engine.process(normalize(env))]
            ok = bool(hits) == (t.get("expect", "alert") == "alert")
            failures += not ok
            print(f"  {'PASS' if ok else 'FAIL'}  {rule.id} on {t['scenario']} ({len(hits)} alerts)")
    sys.exit(1 if failures else 0)


def cmd_graph(args) -> None:
    from aegis.graph.analysis import export_cypher
    from aegis.storage.db import create_repository

    sys.stdout.write(export_cypher(create_repository()))


def cmd_investigate(args) -> None:
    from aegis.investigator import Investigator
    from aegis.storage.db import create_repository

    repo = create_repository()
    inc = repo.get_incident(args.incident_id)
    if not inc:
        sys.exit("incident not found")
    report = Investigator(repo).investigate(inc, use_llm=not args.no_llm)
    print(report.model_dump_json(indent=2))


def main(argv: list[str] | None = None) -> None:
    logging.basicConfig(level=logging.WARNING, format="%(levelname)s %(name)s: %(message)s")
    p = argparse.ArgumentParser(prog="aegis", description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = p.add_subparsers(dest="cmd", required=True)

    d = sub.add_parser("demo", help="run the whole pipeline in-process")
    d.add_argument("--scenario", default="credential_compromise", help="scenario name or 'all'")
    d.add_argument("--warmup-days", type=float, default=2)
    d.add_argument("--serve", action="store_true", help="start the dashboard afterwards")
    d.add_argument("--live", action="store_true", help="keep generating benign traffic while serving")
    d.add_argument("--attack-every", type=float, default=0, help="with --live: inject an attack every N seconds")
    d.add_argument("--host", default="127.0.0.1")
    d.add_argument("--port", type=int, default=8000)
    d.add_argument("--no-llm", action="store_true", help="use the template investigator only")
    d.add_argument("--keep", action="store_true", help="keep the existing demo database")
    d.set_defaults(func=cmd_demo)

    t = sub.add_parser("train", help="train and evaluate ML models")
    t.add_argument("--seed", type=int, default=7)
    t.set_defaults(func=cmd_train)

    r = sub.add_parser("run", help="run a microservice")
    r.add_argument("service", choices=["generator", "collector", "auth-analyzer", "cloud-analyzer", "network-analyzer",
                                       "ml-inference", "indexer", "correlator", "investigator"])
    r.set_defaults(func=cmd_run)

    a = sub.add_parser("api", help="run the API + dashboard (remote mode)")
    a.add_argument("--host", default="0.0.0.0")
    a.add_argument("--port", type=int, default=8000)
    a.set_defaults(func=cmd_api)

    s = sub.add_parser("simulate", help="publish an attack scenario to the bus")
    s.add_argument("scenario")
    s.add_argument("--seed", type=int, default=None)
    s.set_defaults(func=cmd_simulate)

    g = sub.add_parser("generate", help="print synthetic raw logs as JSON lines")
    g.add_argument("--days", type=float, default=1)
    g.add_argument("--seed", type=int, default=7)
    g.add_argument("--attacks-per-day", type=float, default=2)
    g.set_defaults(func=cmd_generate)

    rp = sub.add_parser("replay", help="publish raw logs from a JSON-lines file")
    rp.add_argument("file")
    rp.set_defaults(func=cmd_replay)

    ru = sub.add_parser("rules", help="rule tooling")
    ru.add_argument("action", choices=["validate"])
    ru.set_defaults(func=cmd_rules)

    gr = sub.add_parser("graph", help="graph tooling")
    gr.add_argument("action", choices=["export-cypher"])
    gr.set_defaults(func=cmd_graph)

    inv = sub.add_parser("investigate", help="investigate an incident")
    inv.add_argument("incident_id", type=int)
    inv.add_argument("--no-llm", action="store_true")
    inv.set_defaults(func=cmd_investigate)

    args = p.parse_args(argv)
    args.func(args)


if __name__ == "__main__":
    main()
